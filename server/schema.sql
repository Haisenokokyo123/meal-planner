-- Sakto Meals · MariaDB 10.4+ / MySQL 8.0+ · UTF-8 / InnoDB.
-- Import into a database named sakto_meals in phpMyAdmin, then run scripts/setup.php.
-- Non-destructive: existing tables/data are preserved. All timestamps stored as UTC.
SET NAMES utf8mb4;
SET time_zone = '+00:00';
CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
  deletedAt DATETIME(3) NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT users_role CHECK (role IN ('CUSTOMER','ADMIN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS sessions (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  tokenHash CHAR(64) NOT NULL UNIQUE,
  userId VARCHAR(100) NOT NULL,
  expiresAt DATETIME(3) NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX sessions_user (userId), INDEX sessions_expiry (expiresAt),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS reset_tokens (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  tokenHash CHAR(64) NOT NULL UNIQUE,
  userId VARCHAR(100) NOT NULL,
  expiresAt DATETIME(3) NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX reset_user (userId),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS rate_limits (
  `key` CHAR(64) NOT NULL PRIMARY KEY,
  `count` INT UNSIGNED NOT NULL,
  expiresAt DATETIME(3) NOT NULL,
  INDEX rate_expiry (expiresAt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS profiles (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  userId VARCHAR(100) NOT NULL UNIQUE,
  data LONGTEXT NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS meals (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  slug VARCHAR(100) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  category VARCHAR(50) NOT NULL,
  price INT UNSIGNED NOT NULL,
  calories INT UNSIGNED NOT NULL,
  protein DOUBLE NOT NULL,
  carbs DOUBLE NOT NULL,
  fat DOUBLE NOT NULL,
  servingSize VARCHAR(150) NOT NULL,
  ingredients LONGTEXT NOT NULL,
  allergens LONGTEXT NOT NULL,
  tags LONGTEXT NOT NULL,
  slots LONGTEXT NOT NULL,
  image VARCHAR(200) NOT NULL,
  available BOOLEAN NOT NULL DEFAULT TRUE,
  capacity INT UNSIGNED NOT NULL DEFAULT 100,
  portions LONGTEXT NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT meal_money CHECK (price > 0),
  CONSTRAINT meal_nutrition CHECK (calories > 0 AND protein >= 0 AND carbs >= 0 AND fat >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS plans (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  userId VARCHAR(100) NOT NULL,
  weekStart CHAR(10) NOT NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  profileData LONGTEXT NOT NULL,
  nutritionData LONGTEXT NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX plan_user_week (userId,weekStart),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT plan_status CHECK (status IN ('DRAFT','CONFIRMED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS plan_slots (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  planId VARCHAR(100) NOT NULL,
  mealId VARCHAR(100) NOT NULL,
  day INT NOT NULL,
  slot VARCHAR(20) NOT NULL,
  `portion` DOUBLE NOT NULL DEFAULT 1,
  locked BOOLEAN NOT NULL DEFAULT FALSE,
  explanation TEXT NOT NULL,
  UNIQUE KEY plan_day_slot (planId,day,slot),
  FOREIGN KEY (planId) REFERENCES plans(id) ON DELETE CASCADE,
  FOREIGN KEY (mealId) REFERENCES meals(id) ON DELETE RESTRICT,
  CONSTRAINT plan_slot_day CHECK (day BETWEEN 0 AND 6),
  CONSTRAINT plan_slot_time CHECK (slot IN ('breakfast','lunch','dinner')),
  CONSTRAINT plan_portion CHECK (`portion` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS packages (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  mealCount INT UNSIGNED NOT NULL,
  price INT UNSIGNED NOT NULL,
  description TEXT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS delivery_zones (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  fee INT UNSIGNED NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS settings (
  id VARCHAR(100) NOT NULL PRIMARY KEY DEFAULT 'main',
  cutoffHours INT UNSIGNED NOT NULL DEFAULT 24,
  deliveryWindow VARCHAR(100) NOT NULL DEFAULT '8:00 AM – 12:00 PM',
  supportedDays LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS subscriptions (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  userId VARCHAR(100) NOT NULL,
  packageId VARCHAR(100) NOT NULL,
  packageName VARCHAR(80) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  weekStart CHAR(10) NOT NULL,
  nextCycle CHAR(10) NOT NULL,
  mealCount INT UNSIGNED NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX sub_user_status (userId,status),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE RESTRICT,
  FOREIGN KEY (packageId) REFERENCES packages(id) ON DELETE RESTRICT,
  CONSTRAINT sub_status CHECK (status IN ('ACTIVE','PAUSED','CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS orders (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  userId VARCHAR(100) NOT NULL,
  planId VARCHAR(100) NULL UNIQUE,
  subscriptionId VARCHAR(100) NOT NULL UNIQUE,
  idempotencyKey VARCHAR(100) NOT NULL,
  payloadHash CHAR(64) NOT NULL,
  status VARCHAR(25) NOT NULL DEFAULT 'CONFIRMED',
  mealTotal INT UNSIGNED NOT NULL,
  deliveryFee INT UNSIGNED NOT NULL,
  total INT UNSIGNED NOT NULL,
  address VARCHAR(500) NOT NULL,
  zoneName VARCHAR(100) NOT NULL,
  paymentMethod VARCHAR(20) NOT NULL,
  paymentStatus VARCHAR(30) NOT NULL DEFAULT 'SIMULATED_PAID',
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY order_idempotency (userId,idempotencyKey),
  INDEX order_status_created (status,createdAt),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE RESTRICT,
  FOREIGN KEY (planId) REFERENCES plans(id) ON DELETE SET NULL,
  FOREIGN KEY (subscriptionId) REFERENCES subscriptions(id) ON DELETE RESTRICT,
  CONSTRAINT order_status CHECK (status IN ('CONFIRMED','PREPARING','OUT_FOR_DELIVERY','DELIVERED','CANCELLED')),
  CONSTRAINT order_payment CHECK (paymentMethod IN ('GCash','Maya','Card')),
  CONSTRAINT order_totals CHECK (total = mealTotal + deliveryFee)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS order_items (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  orderId VARCHAR(100) NOT NULL,
  mealId VARCHAR(100) NOT NULL,
  name VARCHAR(100) NOT NULL,
  day INT NOT NULL,
  slot VARCHAR(20) NOT NULL,
  deliveryDate CHAR(10) NOT NULL,
  `portion` DOUBLE NOT NULL,
  price INT UNSIGNED NOT NULL,
  calories DOUBLE NOT NULL,
  protein DOUBLE NOT NULL,
  carbs DOUBLE NOT NULL,
  fat DOUBLE NOT NULL,
  INDEX order_item_day_meal (deliveryDate,mealId),
  FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE CASCADE,
  FOREIGN KEY (mealId) REFERENCES meals(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS order_history (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  orderId VARCHAR(100) NOT NULL,
  status VARCHAR(25) NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS weights (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  userId VARCHAR(100) NOT NULL,
  weight DOUBLE NOT NULL,
  date CHAR(10) NOT NULL,
  UNIQUE KEY weight_user_date (userId,date),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS favorites (
  userId VARCHAR(100) NOT NULL,
  mealId VARCHAR(100) NOT NULL,
  PRIMARY KEY (userId,mealId),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (mealId) REFERENCES meals(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS contact_messages (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(254) NOT NULL,
  message TEXT NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS audit_logs (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  userId VARCHAR(100) NOT NULL,
  action TEXT NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX audit_created (createdAt),
  FOREIGN KEY (userId) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
